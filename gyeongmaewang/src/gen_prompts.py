def slots():
  S = []
  for ch, rows in OPENINGS.items():
    nm = HERO[ch][0]
    for sid, desc, when in rows: S.append({"id":sid, "kind":"cut", "title":f"{nm} 오프닝 — {when}", "desc":desc, "use":"오프닝"})
  for cid, nm, why, look, a, b, c in OCCS:
    for ex, t in (("normal", a), ("angry", b), ("worried", c)):
      S.append({"id":f"npc_occ_{cid}_{ex}", "kind":"npc", "title":f"{cid} {nm} — {ex}", "desc":look + " / " + t, "use":"이 물건 전용 점유자"})
  for cid, t, ext, door, inn in CASES:
    for k, d, u in (("ext", ext, "외관 — 조사·입찰"), ("door", door, "현관·복도 — 명도"), ("in", inn, "문을 연 집 — 하자·수리")):
      S.append({"id":f"bg_case_{cid}_{k}", "kind":"bg", "title":f"{cid} {t} — {u}", "desc":d, "use":"이 물건 전용 배경"})
  return S

