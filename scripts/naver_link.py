"""
5절에서 이미 구해둔 대상 물건 좌표로, 네이버부동산 지도 화면을 "그 동네
빌라·매매만 미리 필터링된" 상태로 새 탭에서 열 수 있는 딥링크를 만든다.

실거래가(3~8절)는 "이미 팔린 가격"이고, 11절의 붙여넣기 방식은 "지금 나온
호가"를 사용자가 직접 복사해서 넣어야 하는데, 그마저 귀찮으면 아예 안 보고
넘어가는 경우가 많다. 이 절은 그 마지막 단계 — "그 화면을 아예 눌러서
바로 열어보기" — 만 자동화한다. 스크래핑이 아니라 URL 하나만 만들어서
사용자가 직접 클릭해서 여는 것뿐이라 11절의 "자동 수집 금지" 원칙과
충돌하지 않는다(11절이 막는 건 "결과를 긁어와 대신 보여주는 것"이고, 이건
"사용자를 그 화면으로 안내"하는 것일 뿐 결과를 읽어오지 않는다).

⚠️ URL 파라미터(a=VL 빌라, b=A1 매매, ms=위경도,줌)는 공개적으로 알려진
네이버부동산 지도 딥링크 규칙을 참고해 구성한 것이다 — 네이버 공식 문서로
검증한 스펙은 아니다(21절 경기데이터드림 API와 같은 성격의 "추정" 스펙).
실제로 열었을 때 필터·위치가 다르게 적용되면 사용자가 실제 URL/화면을
보여주는 대로 고친다.
"""

# 거래종류(b): A1=매매, B1=전세, B2=월세
TRADE_TYPE_SALE = "A1"
# 매물종류(a): VL=빌라/연립다세대
ARTICLE_TYPE_VILLA = "VL"


def naver_land_url(lat: float, lon: float, zoom: int = 17,
                    article_type: str = ARTICLE_TYPE_VILLA,
                    trade_type: str = TRADE_TYPE_SALE) -> str:
    """대상 물건 좌표를 지도 중심으로 하는 네이버부동산 딥링크.
    zoom 17이면 동 단위 정도로 좁혀서 보여준다(숫자가 클수록 확대)."""
    return f"https://new.land.naver.com/houses?ms={lat:.6f},{lon:.6f},{zoom}&a={article_type}&b={trade_type}"
